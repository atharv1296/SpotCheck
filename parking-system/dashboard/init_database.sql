-- ============================================================================
-- TABLE 3: PARKING_APP_PARKINGSESSION
-- Stores parking session records (entry/exit tracking)
-- ============================================================================
PROMPT
PROMPT Creating PARKING_APP_PARKINGSESSION table...
PROMPT

CREATE TABLE PARKING_APP_PARKINGSESSION (
    ID NUMBER(11) NOT NULL,
    VEHICLE_ID NUMBER(11) NOT NULL,
    PARKING_SLOT_ID NUMBER(11) NOT NULL,
    ENTRY_TIME TIMESTAMP(6) NOT NULL,
    EXIT_TIME TIMESTAMP(6),
    STATUS VARCHAR2(10) DEFAULT 'Active' NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    
    -- Constraints
    CONSTRAINT PK_PARKINGSESSION PRIMARY KEY (ID),
    CONSTRAINT FK_SESSION_VEHICLE FOREIGN KEY (VEHICLE_ID) 
        REFERENCES PARKING_APP_VEHICLE(ID) ON DELETE CASCADE,
    CONSTRAINT FK_SESSION_SLOT FOREIGN KEY (PARKING_SLOT_ID) 
        REFERENCES PARKING_APP_PARKINGSLOT(ID) ON DELETE CASCADE,
    CONSTRAINT CHK_SESSION_STATUS CHECK (STATUS IN ('Active', 'Completed')),
    CONSTRAINT CHK_SESSION_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

-- Create indexes for faster queries
CREATE INDEX IDX_SESSION_VEHICLE ON PARKING_APP_PARKINGSESSION(VEHICLE_ID);
CREATE INDEX IDX_SESSION_SLOT ON PARKING_APP_PARKINGSESSION(PARKING_SLOT_ID);
CREATE INDEX IDX_SESSION_STATUS ON PARKING_APP_PARKINGSESSION(STATUS);
CREATE INDEX IDX_SESSION_ACTIVE ON PARKING_APP_PARKINGSESSION(IS_ACTIVE);
CREATE INDEX IDX_SESSION_ENTRY ON PARKING_APP_PARKINGSESSION(ENTRY_TIME);

-- Unique constraint: Only one active session per slot
CREATE UNIQUE INDEX UQ_ACTIVE_SESSION_PER_SLOT 
    ON PARKING_APP_PARKINGSESSION(PARKING_SLOT_ID) 
    WHERE IS_ACTIVE = 1;

