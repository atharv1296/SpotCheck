CREATE TABLE PARKING_APP_VEHICLE (
    ID NUMBER(11) NOT NULL,
    LICENSE_PLATE VARCHAR2(20) NOT NULL,
    OWNER_CONTACT VARCHAR2(15),
    VEHICLE_TYPE VARCHAR2(20) NOT NULL,
    REGISTERED_STATE VARCHAR2(2),
    CONTACT_NUMBER VARCHAR2(15),
    CREATED_AT TIMESTAMP(6) NOT NULL,
    OWNER_NAME VARCHAR2(100),
    
    -- Constraints
    CONSTRAINT PK_VEHICLE PRIMARY KEY (ID),
    CONSTRAINT UQ_VEHICLE_LICENSE UNIQUE (LICENSE_PLATE),
    CONSTRAINT CHK_VEHICLE_TYPE CHECK (VEHICLE_TYPE IN ('two_wheeler', 'sedan', 'suv', 'large')),
    CONSTRAINT CHK_REGISTERED_STATE CHECK (REGISTERED_STATE IN (
        'AN', 'AP', 'AR', 'AS', 'BR', 'CH', 'CG', 'DH', 'DD', 'DL',
        'GA', 'GJ', 'HR', 'HP', 'JK', 'JH', 'KA', 'KL', 'LD', 'MP',
        'MH', 'MN', 'ML', 'MZ', 'NL', 'OR', 'PY', 'PB', 'RJ', 'SK',
        'TN', 'TS', 'TR', 'UP', 'UK', 'WB'
    ))
);

-- Create index for faster lookups
CREATE INDEX IDX_VEHICLE_LICENSE ON PARKING_APP_VEHICLE(LICENSE_PLATE);
CREATE INDEX IDX_VEHICLE_TYPE ON PARKING_APP_VEHICLE(VEHICLE_TYPE);

